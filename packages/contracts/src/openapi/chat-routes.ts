import * as z from 'zod';

import {
  AddGroupMembersBody,
  AttachmentParams,
  ChatPeopleQuery,
  ChatPersonDto,
  ConversationDetailDto,
  ConversationDto,
  ConversationMemberParams,
  ConversationParams,
  CreateDirectBody,
  CreateGroupBody,
  DownloadUrlDto,
  EditMessageBody,
  ListConversationsQuery,
  ListMessagesQuery,
  MarkReadBody,
  MessageDto,
  MessageParams,
  MuteBody,
  RenameGroupBody,
  SendMessageBody,
  TransferOwnerBody,
  UnreadCountDto,
  UploadQuery,
  UploadResponseDto,
  WorkspaceConversationParams,
} from '../chat/chat.schemas';
import type { ApiRoute } from './routes';

// Mốc 6 — trò chuyện (avatar-chat.md §4, ADR-143…146; T-069). Mọi route qua cổng công ty ⇒ SESSION_REVOKED.

const CONV = '/chat/conversations/{id}';
const UploadHeaders = z.object({ 'x-upload-name': z.string().min(1).max(765) });
const base = { tag: 'chat', security: 'bearer' } as const;
const RULE = ['SESSION_REVOKED', 'BUSINESS_RULE_VIOLATION'] as const;

export const CHAT_API_ROUTES: readonly ApiRoute[] = [
  {
    ...base,
    method: 'get',
    path: '/chat/people',
    summary: 'Danh bạ nội bộ: người thuộc công ty hoạt động — không email (R49)',
    query: ChatPeopleQuery,
    response: { status: 200, data: z.array(ChatPersonDto) },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'get',
    path: '/chat/conversations',
    summary: 'Hội thoại của tôi — keyset theo tin cuối (unread, muted, canSend)',
    query: ListConversationsQuery,
    response: { status: 200, data: z.array(ConversationDto), paged: true },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'get',
    path: '/chat/unread-count',
    summary: 'Tổng tin chưa đọc cho badge (bỏ hội thoại tắt tiếng)',
    response: { status: 200, data: UnreadCountDto },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'post',
    path: '/chat/direct',
    summary: 'Tạo-hoặc-lấy hội thoại 1-1 (201 mới tạo / 200 đã có)',
    body: CreateDirectBody,
    response: { status: 201, data: ConversationDetailDto, alsoOk: true },
    errors: RULE,
  },
  {
    ...base,
    method: 'post',
    path: '/chat/groups',
    summary: 'Tạo nhóm — người tạo là OWNER',
    body: CreateGroupBody,
    response: { status: 201, data: ConversationDetailDto },
    errors: RULE,
  },
  {
    ...base,
    method: 'put',
    path: '/chat/workspaces/{wsId}/conversation',
    summary: 'Tạo-hoặc-lấy phòng của workspace (thành viên ws hiện tại)',
    params: WorkspaceConversationParams,
    response: { status: 201, data: ConversationDetailDto, alsoOk: true },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'get',
    path: CONV,
    summary: 'Chi tiết hội thoại + thành viên (không phải người tham gia ⇒ 404)',
    params: ConversationParams,
    response: { status: 200, data: ConversationDetailDto },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'patch',
    path: CONV,
    summary: 'Đổi tên nhóm (OWNER)',
    params: ConversationParams,
    body: RenameGroupBody,
    response: { status: 200, data: ConversationDetailDto },
    errors: RULE,
  },
  {
    ...base,
    method: 'post',
    path: `${CONV}/members`,
    summary: 'Thêm thành viên nhóm (OWNER)',
    params: ConversationParams,
    body: AddGroupMembersBody,
    response: { status: 200, data: ConversationDetailDto },
    errors: RULE,
  },
  {
    ...base,
    method: 'delete',
    path: `${CONV}/members/{userId}`,
    summary: 'Bớt thành viên nhóm (OWNER) — người bị bớt mất quyền đọc cả lịch sử',
    params: ConversationMemberParams,
    response: { status: 200, data: ConversationDetailDto },
    errors: RULE,
  },
  {
    ...base,
    method: 'put',
    path: `${CONV}/owner`,
    summary: 'Giao quyền OWNER',
    params: ConversationParams,
    body: TransferOwnerBody,
    response: { status: 200, data: ConversationDetailDto },
    errors: RULE,
  },
  {
    ...base,
    method: 'post',
    path: `${CONV}/leave`,
    summary: 'Rời nhóm',
    params: ConversationParams,
    response: { status: 204 },
    errors: RULE,
  },
  {
    ...base,
    method: 'put',
    path: `${CONV}/mute`,
    summary: 'Tắt / bật tiếng hội thoại',
    params: ConversationParams,
    body: MuteBody,
    response: { status: 204 },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'put',
    path: `${CONV}/read`,
    summary: 'Đánh dấu đã đọc tới tin (chỉ tiến)',
    params: ConversationParams,
    body: MarkReadBody,
    response: { status: 204 },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'get',
    path: `${CONV}/messages`,
    summary: 'Tin nhắn — keyset before / after, luôn tăng dần',
    params: ConversationParams,
    query: ListMessagesQuery,
    response: { status: 200, data: z.array(MessageDto), paged: true },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'post',
    path: `${CONV}/messages`,
    summary: 'Gửi tin — idempotent theo clientMsgId (gửi lại giống ⇒ 200 tin cũ)',
    params: ConversationParams,
    body: SendMessageBody,
    response: { status: 201, data: MessageDto, alsoOk: true },
    errors: RULE,
  },
  {
    ...base,
    method: 'patch',
    path: '/chat/messages/{id}',
    summary: 'Sửa tin của mình (≤ 15 phút)',
    params: MessageParams,
    body: EditMessageBody,
    response: { status: 200, data: MessageDto },
    errors: RULE,
  },
  {
    ...base,
    method: 'delete',
    path: '/chat/messages/{id}',
    summary: 'Xóa tin của mình — đính kèm 404 ngay',
    params: MessageParams,
    response: { status: 204 },
    errors: ['SESSION_REVOKED'],
  },
  {
    ...base,
    method: 'post',
    path: '/chat/uploads',
    summary: 'Tải lên đính kèm — thân nhị phân ≤ 20 MB, tên gốc trong X-Upload-Name',
    query: UploadQuery,
    headers: UploadHeaders,
    binaryBody: true,
    response: { status: 201, data: UploadResponseDto },
    errors: [
      'SESSION_REVOKED',
      'INVALID_UPLOAD_NAME',
      'PAYLOAD_TOO_LARGE',
      'UNSUPPORTED_MEDIA_TYPE',
      'UNSUPPORTED_FILE_TYPE',
      'MACRO_OR_ACTIVE_CONTENT',
      'BUSINESS_RULE_VIOLATION',
      'IMAGE_PROCESSING_BUSY',
      'IMAGE_PROCESSING_UNAVAILABLE',
      'STORAGE_FULL',
      'SERVICE_UNAVAILABLE',
    ],
  },
  {
    ...base,
    method: 'post',
    path: '/chat/attachments/{id}/download-url',
    summary: 'URL tải tệp (60 s) — kiểm quyền lúc bấm',
    params: AttachmentParams,
    response: { status: 200, data: DownloadUrlDto },
    errors: ['SESSION_REVOKED'],
  },
];
